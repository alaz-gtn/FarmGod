"""Genera FarmGod/Recipes.lua, las recetas para el coste de fabricación del tooltip, con los datos
de AtlasLoot Forever (AtlasLootClassic, GPL). Así FarmGod no necesita ningún addon de recetas en el juego.

Uso: python -I gen_recipes.py [AtlasLootClassic/Data/Profession.lua]
Sin ruta, lee el AtlasLoot instalado en WoW Forever.

AtlasLoot escribe cada receta así:
    [hechizo] = { objetoCreado, profesión, nivelMínimo, nivelBajo, nivelAlto, { materiales }, { cantidades }, cuántosCrea }
Solo vale su tabla Classic, la que carga Forever, que incluye su parte "Forever Classic"; las de TBC
y Wrath son de otros clientes. Se quedan fuera las recetas que no crean un objeto (encantar equipo).
Recipes.lua va por objeto creado, con todas las recetas que lo hacen:
    { profesión, nivel, cuántosCrea, material1, cantidad1, material2, cantidad2, ... }
El tooltip elige la más barata con los precios del momento.
"""
import re
import sys
from datetime import date
from pathlib import Path

DEFAULT = Path(r"C:\Program Files (x86)\World of Warcraft\_forever_\Interface\AddOns\AtlasLootClassic\Data\Profession.lua")
source = Path(sys.argv[1]) if len(sys.argv) > 1 else DEFAULT
root = Path(__file__).resolve().parent.parent
out = root / "FarmGod" / "Recipes.lua"

text = source.read_text(encoding="utf-8")
start = text.index("PROFESSION_DATA.CLASSIC = {")
end = text.index("if AtlasLoot:GameVersion_GE(AtlasLoot.BC_VERSION_NUM)", start)
block = text[start:end]
toc = source.parent.parent / "AtlasLootClassic_Forever.toc"
version = "?"
if toc.exists():
    m = re.search(r"^## Version:\s*(\S+)", toc.read_text(encoding="utf-8"), re.M)
    if m:
        version = m.group(1)

ROW = re.compile(r"\[(\d+)\]\s*=\s*\{\s*(nil|\d+)\s*,\s*(\d+)\s*,\s*(\d+)\s*,\s*(\d+)\s*,\s*(\d+)\s*,"
                 r"\s*\{([^}]*)\}\s*,\s*\{([^}]*)\}\s*(?:,\s*(\d+)\s*)?\}")
recipes = {}
spells = skipped = 0
for spell, created, prof, skill, _low, _high, reagents, counts, made in ROW.findall(block):
    spells += 1
    ids = [int(x) for x in reagents.replace(" ", "").split(",") if x]
    nums = [int(x) for x in counts.replace(" ", "").split(",") if x]
    if created == "nil" or not ids or len(ids) != len(nums):
        skipped += 1
        continue
    row = [int(prof), int(skill), int(made or 1)]
    for i, n in zip(ids, nums):
        row += [i, n]
    item = int(created)
    if row not in recipes.setdefault(item, []):
        recipes[item].append(row)

lines = [
    "local _, ns = ...",
    "",
    f"-- Generated by tools/gen_recipes.py on {date.today().isoformat()} from AtlasLoot Forever {version}",
    "-- (AtlasLootClassic, GPL; its Classic table, with the recipes Forever added). Don't edit: run the script again.",
    "-- By created item: each recipe that makes it as { profession, skill, made, reagent, count, reagent, count, ... }",
    "-- Professions as AtlasLoot numbers them: 1 First Aid, 2 Blacksmithing, 3 Leatherworking, 4 Alchemy,",
    "-- 6 Cooking, 7 Mining, 8 Tailoring, 9 Engineering, 10 Enchanting, 13 Poisons",
    "ns.RECIPES = {",
]
for item in sorted(recipes):
    rows = ", ".join("{ " + ", ".join(str(v) for v in row) + " }" for row in recipes[item])
    lines.append(f"\t[{item}] = {{ {rows} }},")
lines.append("}")
out.write_text("\n".join(lines) + "\n", encoding="utf-8")
several = sum(1 for v in recipes.values() if len(v) > 1)
print(f"{out}: {len(recipes)} objetos de {spells} recetas ({skipped} sin objeto), {several} con más de una receta")
